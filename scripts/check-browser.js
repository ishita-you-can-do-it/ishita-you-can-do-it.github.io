import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdir } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { chromium } from 'playwright';
import { DURATION } from '../exam-core.js';

const server = spawn(process.execPath, ['scripts/serve.js'], { env: { ...process.env, PORT: '4180' }, stdio: ['ignore', 'pipe', 'inherit'] });
let browser;
const STORE = 'ugc-net-march-2023-v1';
const screenshots = '/tmp/ugc-net-browser-checks';
const errors = [];

try {
  const url = await new Promise((resolve, reject) => {
    server.stdout.on('data', chunk => {
      const match = chunk.toString().match(/http:\/\/127\.0\.0\.1:\d+/);
      if (match) resolve(match[0]);
    });
    server.once('error', reject);
    server.once('exit', code => reject(new Error(`Preview server exited: ${code}`)));
  });
  await mkdir(screenshots, { recursive: true });
  browser = await chromium.launch();
  const filePage = await browser.newPage();
  const fileErrors = [];
  filePage.on('pageerror', error => fileErrors.push(error.message));
  await filePage.goto(pathToFileURL(`${process.cwd()}/index.html`).href);
  await filePage.locator('.session-card').first().waitFor();
  assert.equal(await filePage.locator('.session-card').count(), 30);
  await filePage.getByRole('button', { name: /March 2023/ }).click();
  await filePage.locator('[data-action="start"][data-paper="paper2"]').click();
  await filePage.locator('#timer-value').waitFor();
  assert.deepEqual(fileErrors, []);
  await filePage.close();
  console.log('PASS: root index.html loads directly from file:// and starts the exam.');
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(url);
  await page.locator('.session-card').first().waitFor();
  assert.equal(await page.locator('.session-card').count(), 30);
  assert.equal(await page.locator('.session-card:disabled').count(), 29);
  assert.ok(await page.locator('svg').count() > 30);
  await page.screenshot({ path: `${screenshots}/library-desktop.png`, fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: /March 2023/ }).click();
  await page.locator('.paper-card').first().waitFor();
  assert.equal(await page.locator('.paper-card').count(), 2);
  assert.equal(await page.locator('[data-action="start"]:enabled').count(), 2);
  await page.screenshot({ path: `${screenshots}/papers-desktop.png`, animations: 'disabled' });
  await page.locator('[data-action="start"][data-paper="paper2"]').click();
  await page.locator('#timer-value').waitFor();
  assert.match(await page.locator('#timer-value').innerText(), /0[23]:[05][09]:[05][09]/);
  assert.equal(await page.locator('.solution, .accepted-answer').count(), 0);
  await page.locator('.option:has(input[value="C"])').click();
  await page.getByRole('button', { name: 'Mark for review', exact: true }).click();
  const deadline = await page.evaluate(key => JSON.parse(localStorage.getItem(key)).attempt.deadline, STORE);
  await page.reload();
  await page.locator('#timer-value').waitFor();
  assert.equal(await page.evaluate(key => JSON.parse(localStorage.getItem(key)).attempt.deadline, STORE), deadline);
  assert.ok(await page.locator('input[value="C"]').isChecked());
  assert.equal(await page.getByRole('button', { name: 'Marked for review', exact: true }).getAttribute('aria-pressed'), 'true');
  await page.screenshot({ path: `${screenshots}/exam-desktop.png`, animations: 'disabled' });
  await page.getByRole('button', { name: 'Next question' }).click();
  await page.locator('.option:has(input[value="A"])').click();
  await page.getByRole('button', { name: 'Clear answer', exact: true }).click();
  assert.equal(await page.locator('input:checked').count(), 0);
  await page.locator('.option:has(input[value="A"])').click();
  for (const id of [18, 53]) {
    await page.locator(`[data-action="jump"][data-index="${id - 1}"]`).click();
    await page.locator('.option:has(input[value="A"])').click();
  }
  await page.locator('[data-action="jump"][data-index="90"]').click();
  assert.match(await page.locator('.passage').innerText(), /two clay balls/);
  await page.locator('[data-action="jump"][data-index="95"]').click();
  assert.match(await page.locator('.passage').innerText(), /social support/);
  await page.getByRole('button', { name: 'Finish exam', exact: true }).click();
  assert.ok(await page.locator('#submit-dialog').isVisible());
  await page.getByRole('button', { name: 'Continue exam' }).click();
  assert.ok(await page.locator('.question-area').isVisible());
  await page.getByRole('button', { name: 'Finish exam', exact: true }).click();
  await page.getByRole('button', { name: 'Submit exam', exact: true }).click();
  await page.locator('.main-score').waitFor();
  assert.equal(await page.locator('.main-score strong').innerText(), '6 / 200');
  assert.equal(await page.locator('.review-question').count(), 100);
  assert.ok(await page.locator('.solution').first().isVisible());
  assert.equal(await page.evaluate(key => JSON.parse(localStorage.getItem(key)).history.length, STORE), 1);
  await page.screenshot({ path: `${screenshots}/results-desktop.png`, animations: 'disabled' });
  await page.getByRole('tab', { name: 'Incorrect 1', exact: true }).click();
  assert.equal(await page.locator('.review-question').count(), 1);
  await page.getByRole('tab', { name: 'Unanswered 96', exact: true }).click();
  assert.equal(await page.locator('.review-question').count(), 96);
  console.log('PASS: library, paper selection, answer hiding, navigation, review flags, reload, clear, dual keys, passages, submission, score, filters, history.');

  await page.getByRole('button', { name: 'New attempt', exact: true }).click();
  await page.clock.install();
  await page.locator('[data-action="start"][data-paper="paper2"]').click();
  await page.locator('.option:has(input[value="C"])').click();
  await page.clock.fastForward(DURATION + 1000);
  await page.locator('.main-score').waitFor();
  assert.match(await page.locator('.subtitle').innerText(), /Time expired/);
  assert.equal(await page.locator('.main-score strong').innerText(), '2 / 200');
  assert.equal(await page.evaluate(key => JSON.parse(localStorage.getItem(key)).history.length, STORE), 2);
  console.log('PASS: three-hour timeout automatically submits and scores the exam.');

  await page.evaluate(({ key, duration }) => {
    const state = JSON.parse(localStorage.getItem(key));
    const startedAt = Date.now() - duration - 10000;
    state.attempt = { startedAt, deadline: startedAt + duration, answers: { 1: 'C' }, marked: [], index: 0, finishedAt: null };
    localStorage.setItem(key, JSON.stringify(state));
  }, { key: STORE, duration: DURATION });
  await page.reload();
  await page.locator('.main-score').waitFor();
  assert.match(await page.locator('.subtitle').innerText(), /Time expired/);
  assert.equal(await page.evaluate(key => JSON.parse(localStorage.getItem(key)).history.length, STORE), 3);
  await page.reload();
  await page.locator('.main-score').waitFor();
  assert.equal(await page.evaluate(key => JSON.parse(localStorage.getItem(key)).history.length, STORE), 3);
  console.log('PASS: reopening an expired exam submits once, without duplicating history.');

  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    await page.getByRole('link', { name: 'All sessions', exact: true }).click();
    await page.locator('.session-card').first().waitFor();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: `${screenshots}/library-${width}.png`, animations: 'disabled' });
    await page.getByRole('button', { name: /March 2023/ }).click();
    await page.locator('.paper-card').first().waitFor();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: `${screenshots}/papers-${width}.png`, fullPage: true, animations: 'disabled' });
    await page.locator('[data-action="start"][data-paper="paper2"]').click();
    await page.locator('[data-action="jump"][data-index="77"]').click();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: `${screenshots}/exam-${width}.png`, fullPage: true, animations: 'disabled' });
    assert.ok(await page.locator('.timer').isVisible());
    assert.ok(await page.locator('.timer').evaluate(element => element.getBoundingClientRect().top >= 0));
    await page.getByRole('button', { name: 'Finish exam', exact: true }).click();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: `${screenshots}/submission-${width}.png`, animations: 'disabled' });
    await page.getByRole('button', { name: 'Submit exam', exact: true }).click();
    await page.locator('.main-score').waitFor();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    assert.equal(await page.evaluate(() => scrollY), 0);
    await page.screenshot({ path: `${screenshots}/results-${width}.png`, animations: 'disabled' });
  }
  await page.getByRole('button', { name: 'New attempt', exact: true }).click();
  await page.locator('[data-action="start"][data-paper="paper1"]').click();
  await page.locator('.question-area').waitFor();
  assert.equal(await page.locator('.question-number').count(), 50);
  assert.match(await page.locator('.exam-heading').innerText(), /PAPER I · GENERAL APTITUDE/);
  assert.equal(await page.locator('.data-table tbody tr').count(), 6);
  assert.equal(await page.locator('.solution').count(), 0);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: `${screenshots}/paper-one-mobile.png`, animations: 'disabled' });
  await page.locator('.option:has(input[value="B"])').click();
  const paperOneDeadline = await page.evaluate(key => JSON.parse(localStorage.getItem(key)).attempt.deadline, STORE);
  await page.reload();
  await page.locator('.question-area').waitFor();
  assert.equal(await page.locator('.question-number').count(), 50);
  assert.ok(await page.locator('input[value="B"]').isChecked());
  assert.equal(await page.evaluate(key => JSON.parse(localStorage.getItem(key)).attempt.deadline, STORE), paperOneDeadline);
  await page.locator('[data-action="jump"][data-index="49"]').click();
  assert.match(await page.locator('.passage').innerText(), /Gokhale/);
  await page.locator('.option:has(input[value="D"])').click();
  await page.locator('.question-sidebar [data-action="submit"]').click();
  await page.getByRole('button', { name: 'Submit exam', exact: true }).click();
  await page.locator('.main-score').waitFor();
  assert.equal(await page.locator('.main-score strong').innerText(), '4 / 100');
  assert.equal(await page.locator('.review-question').count(), 50);
  assert.equal(await page.locator('.review-question').first().locator('.data-table tbody tr').count(), 6);
  const disputed = page.locator('.review-question').nth(26);
  await disputed.locator('summary').click();
  assert.match(await disputed.locator('.solution').innerText(), /Source\/key note/);
  await page.getByRole('link', { name: 'All sessions', exact: true }).click();
  await page.getByRole('tab', { name: /My attempts/ }).click();
  await page.locator('.attempt-row').first().waitFor();
  assert.match(await page.locator('.attempt-row').first().innerText(), /Paper I: General Aptitude/);
  assert.match(await page.locator('.attempt-row').nth(1).innerText(), /Paper II: Psychology/);
  await page.locator('.attempt-row').nth(1).getByRole('button', { name: 'Review' }).click();
  await page.locator('.main-score').waitFor();
  assert.equal(await page.locator('.review-question').count(), 100);
  await page.getByRole('button', { name: 'New attempt', exact: true }).click();
  await page.locator('[data-action="start"][data-paper="paper1"]').click();
  await page.locator('.question-area').waitFor();
  await page.clock.fastForward(DURATION + 1000);
  await page.locator('.main-score').waitFor();
  assert.equal(await page.locator('.main-score strong').innerText(), '0 / 100');
  assert.match(await page.locator('.subtitle').innerText(), /Time expired/);
  console.log('PASS: Paper I data table, passage, 50-question navigation, reload, 100-mark scoring, source notes, mixed-paper history, and timeout.');
  assert.deepEqual(errors, []);
  console.log(`PASS: desktop and 390px/320px mobile layouts, long questions, dialogs, and results; no browser errors. Screenshots: ${screenshots}`);
} finally {
  await browser?.close();
  server.kill();
}